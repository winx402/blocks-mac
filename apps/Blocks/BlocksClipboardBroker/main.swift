private final class ParentProcessWatchdog: @unchecked Sendable {
    private let parentProcessID: pid_t
    private let beforeExit: @Sendable () -> Void

    init(
        parentProcessID: pid_t = getppid(),
        beforeExit: @escaping @Sendable () -> Void = {}
    ) {
        self.parentProcessID = parentProcessID
        self.beforeExit = beforeExit
    }

    func start() {
        let expectedParentProcessID = parentProcessID
        let beforeExit = beforeExit
        Thread.detachNewThread {
            while true {
                usleep(250_000)
                guard expectedParentProcessID > 1,
                      getppid() == expectedParentProcessID,
                      kill(expectedParentProcessID, 0) == 0 || errno == EPERM else {
                    // Cleanup is best-effort, but process exit is a hard
                    // deadline. SIGALRM terminates the entire helper if any
                    // unexpected filesystem operation fails to return.
                    _ = Darwin.signal(SIGALRM, SIG_DFL)
                    _ = Darwin.alarm(1)
                    beforeExit()
                    Darwin._exit(EXIT_SUCCESS)
                }
            }
        }
    }
}

private final class StagingStore: @unchecked Sendable {
    private let rootDirectory: URL?
    private let rootDescriptor: Int32
    private let rootMetadata: stat?
    let declaredParentProcessID: pid_t

    init(environment: [String: String] = ProcessInfo.processInfo.environment) {
        let declaredParentProcessID = pid_t(
            environment["BLOCKS_CLIPBOARD_PARENT_PID"] ?? ""
        ) ?? 0
        self.declaredParentProcessID = declaredParentProcessID
        guard let rawRoot = environment["BLOCKS_CLIPBOARD_STAGING_ROOT"],
              rawRoot.hasPrefix("/"),
              Self.isExpectedRoot(
                  path: rawRoot,
                  parentProcessID: declaredParentProcessID
              ),
              let expectedDevice = UInt64(
                  environment["BLOCKS_CLIPBOARD_STAGING_DEVICE"] ?? ""
              ),
              let expectedInode = UInt64(
                  environment["BLOCKS_CLIPBOARD_STAGING_INODE"] ?? ""
              ) else {
            rootDirectory = nil
            rootDescriptor = -1
            rootMetadata = nil
            return
        }
        let root = URL(
            fileURLWithPath: rawRoot,
            isDirectory: true
        ).standardizedFileURL
        let descriptor = open(
            root.path,
            O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC
        )
        guard descriptor >= 0 else {
            rootDirectory = nil
            rootDescriptor = -1
            rootMetadata = nil
            return
        }
        var metadata = stat()
        var pathMetadata = stat()
        guard fstat(descriptor, &metadata) == 0,
              Self.isSecureRoot(metadata),
              UInt64(metadata.st_dev) == expectedDevice,
              UInt64(metadata.st_ino) == expectedInode,
              lstat(root.path, &pathMetadata) == 0,
              pathMetadata.st_dev == metadata.st_dev,
              pathMetadata.st_ino == metadata.st_ino else {
            close(descriptor)
            rootDirectory = nil
            rootDescriptor = -1
            rootMetadata = nil
            return
        }
        rootDirectory = root
        rootDescriptor = descriptor
        rootMetadata = metadata
    }

    deinit {
        if rootDescriptor >= 0 {
            close(rootDescriptor)
        }
    }

    func stage(_ data: Data) throws -> ClipboardBrokerDataReference {
        guard let rootDirectory, rootDescriptor >= 0 else {
            throw BrokerFailure.stagingUnavailable
        }

        let token = ClipboardBrokerStaging.makeToken()
        guard ClipboardBrokerStaging.fileURL(
            rootDirectory: rootDirectory,
            token: token
        ) != nil else {
            throw BrokerFailure.stagingReferenceInvalid
        }

        do {
            try writeSecurely(data, token: token)
        } catch {
            removePayload(token: token)
            throw BrokerFailure.stagingWriteFailed
        }
        return .staged(token: token, byteCount: data.count)
    }

    func load(_ reference: ClipboardBrokerDataReference) throws -> Data {
        switch reference {
        case let .inline(data):
            return data
        case let .staged(token, declaredByteCount):
            guard declaredByteCount >= 0,
                  declaredByteCount <= ClipboardBrokerLimits.maxFrameBytes,
                  let rootDirectory,
                  rootDescriptor >= 0,
                  ClipboardBrokerStaging.fileURL(
                    rootDirectory: rootDirectory,
                    token: token
                  ) != nil else {
                throw BrokerFailure.stagingReferenceInvalid
            }

            return try readSecurely(
                token: token,
                expectedByteCount: declaredByteCount
            )
        }
    }

    private func writeSecurely(_ data: Data, token: String) throws {
        let operationRootDescriptor = try duplicatePinnedRootDescriptor()
        defer { close(operationRootDescriptor) }
        let descriptor = openat(
            operationRootDescriptor,
            try payloadName(for: token),
            O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW | O_CLOEXEC,
            mode_t(0o600)
        )
        guard descriptor >= 0 else {
            throw BrokerFailure.stagingWriteFailed
        }
        defer { close(descriptor) }
        var metadata = stat()
        guard fstat(descriptor, &metadata) == 0,
              Self.isSecurePayload(metadata) else {
            throw BrokerFailure.stagingWriteFailed
        }
        try data.withUnsafeBytes { bytes in
            guard let baseAddress = bytes.baseAddress else { return }
            var written = 0
            while written < bytes.count {
                let result = Darwin.write(
                    descriptor,
                    baseAddress.advanced(by: written),
                    bytes.count - written
                )
                guard result > 0 else {
                    throw BrokerFailure.stagingWriteFailed
                }
                written += result
            }
        }
    }

    private func readSecurely(
        token: String,
        expectedByteCount: Int
    ) throws -> Data {
        let operationRootDescriptor = try duplicatePinnedRootDescriptor()
        defer { close(operationRootDescriptor) }
        let descriptor = openat(
            operationRootDescriptor,
            try payloadName(for: token),
            O_RDONLY | O_NOFOLLOW | O_CLOEXEC
        )
        guard descriptor >= 0 else {
            throw BrokerFailure.stagingReferenceInvalid
        }
        defer { close(descriptor) }
        var metadata = stat()
        guard fstat(descriptor, &metadata) == 0,
              Self.isSecurePayload(metadata),
              metadata.st_size >= 0,
              metadata.st_size <= ClipboardBrokerLimits.maxFrameBytes,
              metadata.st_size == expectedByteCount else {
            throw BrokerFailure.stagingReferenceInvalid
        }
        var data = Data(count: expectedByteCount)
        try data.withUnsafeMutableBytes { bytes in
            guard let baseAddress = bytes.baseAddress else { return }
            var readCount = 0
            while readCount < bytes.count {
                let result = Darwin.read(
                    descriptor,
                    baseAddress.advanced(by: readCount),
                    bytes.count - readCount
                )
                guard result > 0 else {
                    throw BrokerFailure.stagingReferenceInvalid
                }
                readCount += result
            }
        }
        return data
    }

    private func removePayload(token: String) {
        guard let operationRootDescriptor = try? duplicatePinnedRootDescriptor(),
              let name = try? payloadName(for: token) else {
            return
        }
        defer { close(operationRootDescriptor) }
        var metadata = stat()
        guard fstatat(
            operationRootDescriptor,
            name,
            &metadata,
            AT_SYMLINK_NOFOLLOW
        ) == 0,
        Self.isSecurePayload(metadata) else {
            return
        }
        _ = unlinkat(operationRootDescriptor, name, 0)
    }

    private func duplicatePinnedRootDescriptor() throws -> Int32 {
        guard rootDescriptor >= 0, let rootMetadata else {
            throw BrokerFailure.stagingUnavailable
        }
        let descriptor = openat(
            rootDescriptor,
            ".",
            O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC
        )
        guard descriptor >= 0 else {
            throw BrokerFailure.stagingUnavailable
        }
        var metadata = stat()
        guard fstat(descriptor, &metadata) == 0,
              metadata.st_dev == rootMetadata.st_dev,
              metadata.st_ino == rootMetadata.st_ino,
              Self.isSecureRoot(metadata) else {
            close(descriptor)
            throw BrokerFailure.stagingUnavailable
        }
        return descriptor
    }

    private func payloadName(for token: String) throws -> String {
        guard let rootDirectory,
              let url = ClipboardBrokerStaging.fileURL(
                  rootDirectory: rootDirectory,
                  token: token
              ) else {
            throw BrokerFailure.stagingReferenceInvalid
        }
        return url.lastPathComponent
    }

    private static func isSecureRoot(_ metadata: stat) -> Bool {
        (metadata.st_mode & S_IFMT) == S_IFDIR
            && metadata.st_uid == geteuid()
            && (metadata.st_mode & mode_t(0o777)) == mode_t(0o700)
    }

    func cleanupPinnedRoot(removingRoot: Bool) -> Int? {
        guard let rootDirectory,
              let rootMetadata,
              let descriptor = try? duplicatePinnedRootDescriptor(),
              let names = Self.directoryEntryNames(
                  descriptor: descriptor,
                  maximumCount: 256
              ) else {
            return nil
        }
        defer { close(descriptor) }

        for name in names {
            guard Self.token(forPayloadName: name) != nil else {
                return nil
            }
            var fileMetadata = stat()
            guard fstatat(
                descriptor,
                name,
                &fileMetadata,
                AT_SYMLINK_NOFOLLOW
            ) == 0,
            (fileMetadata.st_mode & S_IFMT) == S_IFREG,
            fileMetadata.st_uid == geteuid(),
            fileMetadata.st_nlink == 1,
            (fileMetadata.st_mode & mode_t(0o777)) == mode_t(0o600) else {
                return nil
            }
        }

        for name in names {
            guard unlinkat(descriptor, name, 0) == 0 else {
                return nil
            }
        }

        guard removingRoot else { return names.count }
        // Payload deletion is anchored to the pinned descriptor. Root removal
        // is only best-effort and never follows a replacement path.
        var currentMetadata = stat()
        guard lstat(rootDirectory.path, &currentMetadata) == 0,
              currentMetadata.st_dev == rootMetadata.st_dev,
              currentMetadata.st_ino == rootMetadata.st_ino,
              rmdir(rootDirectory.path) == 0 else {
            return nil
        }
        return names.count
    }

    private static func isExpectedRoot(
        path: String,
        parentProcessID: pid_t
    ) -> Bool {
        guard parentProcessID > 1 else { return false }
        let root = URL(
            fileURLWithPath: path,
            isDirectory: true
        ).standardizedFileURL
        guard root.deletingLastPathComponent().standardizedFileURL
            == FileManager.default.temporaryDirectory.standardizedFileURL else {
            return false
        }
        let prefix =
            "\(ClipboardBrokerStaging.directoryName)-\(parentProcessID)-"
        let name = root.lastPathComponent
        guard name.hasPrefix(prefix) else { return false }
        let uuid = String(name.dropFirst(prefix.count))
        return UUID(uuidString: uuid) != nil && uuid == uuid.lowercased()
    }

    private static func isSecurePayload(_ metadata: stat) -> Bool {
        (metadata.st_mode & S_IFMT) == S_IFREG
            && metadata.st_uid == geteuid()
            && metadata.st_nlink == 1
            && (metadata.st_mode & mode_t(0o777)) == mode_t(0o600)
    }

    private static func token(forPayloadName name: String) -> String? {
        let bytes = Array(name.utf8)
        let suffix = Array(".\(ClipboardBrokerStaging.fileExtension)".utf8)
        guard bytes.count == 36 + suffix.count,
              Array(bytes.suffix(suffix.count)) == suffix else {
            return nil
        }
        for index in 0..<36 {
            let byte = bytes[index]
            if [8, 13, 18, 23].contains(index) {
                guard byte == 45 else { return nil }
            } else {
                guard (48...57).contains(byte)
                        || (97...102).contains(byte) else {
                    return nil
                }
            }
        }
        return String(decoding: bytes.prefix(36), as: UTF8.self)
    }

    private static func directoryEntryNames(
        descriptor: Int32,
        maximumCount: Int
    ) -> [String]? {
        let duplicate = openat(
            descriptor,
            ".",
            O_RDONLY | O_DIRECTORY | O_NOFOLLOW | O_CLOEXEC
        )
        guard duplicate >= 0 else { return nil }
        guard let directory = fdopendir(duplicate) else {
            close(duplicate)
            return nil
        }
        defer { closedir(directory) }

        var names: [String] = []
        while true {
            errno = 0
            guard let entry = readdir(directory) else {
                return errno == 0 ? names : nil
            }
            var entryValue = entry.pointee
            let length = Int(entryValue.d_namlen)
            let capacity = MemoryLayout.size(ofValue: entryValue.d_name)
            guard length >= 0, length < capacity else { return nil }
            let name = withUnsafePointer(to: &entryValue.d_name) {
                tuplePointer in
                tuplePointer.withMemoryRebound(
                    to: UInt8.self,
                    capacity: capacity
                ) {
                    String(
                        decoding: UnsafeBufferPointer(
                            start: $0,
                            count: length
                        ),
                        as: UTF8.self
                    )
                }
            }
            guard name != ".", name != ".." else { continue }
            guard names.count < maximumCount else { return nil }
            names.append(name)
        }
        return names
    }
}

private final class ClipboardBrokerServer {
    private enum PasteboardWritePurpose: Equatable {
        case target
        case rollback
    }

    private enum PasteboardPublicationVerification: Equatable {
        case verified
        case changed
        case mismatched
    }

    private enum MaterializedPasteboardWriteResult {
        case published(changeCount: Int)
        case changed
        // The change count is stable, but the native NSURL item published by
        // AppKit was replaced before that count could be sampled.
        case changedBeforePostWriteFence
        case failed
    }

    private struct PostWriteRepresentation {
        let type: NSPasteboard.PasteboardType
        let data: Data
    }

    private struct MaterializedWrite {
        let pasteboardItems: [NSPasteboardWriting]
        let itemCount: Int
        let representationCount: Int
        let byteCount: Int
        let semanticFileURLs: [URL]
        let semanticFileItemIndices: [Int]
        let expectedRepresentations: [Int: [PostWriteRepresentation]]
        let postWriteRepresentations: [Int: [PostWriteRepresentation]]

        init(
            pasteboardItems: [NSPasteboardWriting],
            itemCount: Int,
            representationCount: Int,
            byteCount: Int,
            semanticFileURLs: [URL] = [],
            semanticFileItemIndices: [Int] = [],
            expectedRepresentations: [Int: [PostWriteRepresentation]] = [:],
            postWriteRepresentations: [Int: [PostWriteRepresentation]] = [:]
        ) {
            self.pasteboardItems = pasteboardItems
            self.itemCount = itemCount
            self.representationCount = representationCount
            self.byteCount = byteCount
            self.semanticFileURLs = semanticFileURLs
            self.semanticFileItemIndices = semanticFileItemIndices
            self.expectedRepresentations = expectedRepresentations
            self.postWriteRepresentations = postWriteRepresentations
        }

        static let empty = MaterializedWrite(
            pasteboardItems: [],
            itemCount: 0,
            representationCount: 0,
            byteCount: 0
        )
    }

    private struct PreparedWrite {
        let materialized: MaterializedWrite
        let expectedChangeCount: Int?
        let capturedChangeCount: Int
        let expiresAtSystemUptime: TimeInterval
    }

    private static let maximumPreparedWrites = 8
    private static var preparedWriteLifetime: TimeInterval {
#if DEBUG
        if let rawValue = ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_PREPARED_WRITE_LIFETIME"
        ], let value = TimeInterval(rawValue), value.isFinite, value > 0 {
            return value
        }
#endif
        return 15
    }
    private let pasteboardProvider: () -> NSPasteboard
    private let input: FileHandle
    private let output: FileHandle
    private let stagingStore: StagingStore
    private var inputBuffer = Data()
    private var preparedWrites: [UUID: PreparedWrite] = [:]
    private lazy var pasteboard = pasteboardProvider()
#if DEBUG
    private let testInstrumentation = ClipboardBrokerTestInstrumentation()
#endif

    init(
        pasteboardProvider: @escaping () -> NSPasteboard = {
            NSPasteboard.general
        },
        input: FileHandle = .standardInput,
        output: FileHandle = .standardOutput,
        stagingStore: StagingStore
    ) {
        self.pasteboardProvider = pasteboardProvider
        self.input = input
        self.output = output
        self.stagingStore = stagingStore
    }

    func run() throws {
        while true {
            while let payload = try ClipboardBrokerFrameCodec.takePayload(from: &inputBuffer) {
                let request = try PropertyListDecoder().decode(
                    ClipboardBrokerRequestEnvelope.self,
                    from: payload
                )
                if try !handle(request) {
                    return
                }
            }

            pruneExpiredPreparedWrites()
            let chunk = try readInputChunk()
            guard !chunk.isEmpty else { return }
            inputBuffer.append(chunk)
        }
    }

    private func readInputChunk() throws -> Data {
        var bytes = [UInt8](repeating: 0, count: 64 * 1024)
        while true {
            var descriptor = pollfd(
                fd: input.fileDescriptor,
                events: Int16(POLLIN),
                revents: 0
            )
            let timeoutMilliseconds = preparedWritePollTimeoutMilliseconds()
            let pollResult = Darwin.poll(&descriptor, 1, timeoutMilliseconds)
            if pollResult == 0 {
                pruneExpiredPreparedWrites()
                continue
            }
            if pollResult < 0 {
                if errno == EINTR { continue }
                throw POSIXError(POSIXErrorCode(rawValue: errno) ?? .EIO)
            }
            let count = bytes.withUnsafeMutableBytes {
                Darwin.read(input.fileDescriptor, $0.baseAddress, $0.count)
            }
            if count > 0 {
                return Data(bytes.prefix(Int(count)))
            }
            if count == 0 {
                return Data()
            }
            if errno != EINTR {
                throw POSIXError(POSIXErrorCode(rawValue: errno) ?? .EIO)
            }
        }
    }

    private func preparedWritePollTimeoutMilliseconds() -> Int32 {
        guard let earliestExpiry = preparedWrites.values.map(
            \.expiresAtSystemUptime
        ).min() else {
            return -1
        }
        let remaining = max(
            0,
            earliestExpiry - ProcessInfo.processInfo.systemUptime
        )
        let milliseconds = min(
            ceil(remaining * 1_000),
            Double(Int32.max)
        )
        return Int32(milliseconds)
    }

    private func handle(_ request: ClipboardBrokerRequestEnvelope) throws -> Bool {
        let startedAt = DispatchTime.now().uptimeNanoseconds
        let operation = request.command.operation
        try send(
            ClipboardBrokerResponseEnvelope(
                requestID: request.requestID,
                event: .started(operation: operation, changeCount: nil)
            )
        )
        let startMessage = "request_start id=\(request.requestID.uuidString) operation=\(operation.rawValue) pid=\(getpid())"
        if operation == .observe || operation == .baseline {
            clipboardBrokerLogger.debug("\(startMessage, privacy: .public)")
        } else {
            clipboardBrokerLogger.info("\(startMessage, privacy: .public)")
        }

        let outcome: BrokerOutcome
        do {
            outcome = try execute(request.command, requestID: request.requestID)
        } catch let error as BrokerFailure {
            outcome = failureOutcome(code: failureCode(for: error))
        } catch {
            outcome = failureOutcome(code: "internal_error")
        }

        try send(
            ClipboardBrokerResponseEnvelope(
                requestID: request.requestID,
                event: .terminal(outcome.terminal)
            )
        )
        logTerminal(
            requestID: request.requestID,
            operation: operation,
            startedAt: startedAt,
            metrics: outcome.metrics
        )

        if case .shutdown = request.command {
            return false
        }
        return true
    }

    private func execute(
        _ command: ClipboardBrokerCommand,
        requestID: UUID
    ) throws -> BrokerOutcome {
        switch command {
        case let .observe(request):
            return try observe(request, requestID: requestID)
        case let .resolve(request):
            return try resolve(request, requestID: requestID)
        case let .write(request):
            return try write(request, requestID: requestID)
        case let .prepareWrite(request):
            return try prepareWrite(request)
        case let .commitWrite(request):
            return try commitWrite(request, requestID: requestID)
        case let .cancelWrite(request):
            return try cancelWrite(request)
        case let .validate(request):
            return validate(request)
        case let .currentPlainText(request):
            return try currentPlainText(request, requestID: requestID)
        case let .snapshot(request):
            return try snapshot(request, requestID: requestID)
        case .baseline:
#if DEBUG
            if ProcessInfo.processInfo.environment[
                "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
            ] == "block_baseline" {
                while true {
                    usleep(250_000)
                }
            }
            if let rawCount = ProcessInfo.processInfo.environment[
                "BLOCKS_CLIPBOARD_BROKER_TEST_BASELINE_CHANGE_COUNT"
            ], let count = Int(rawCount) {
                return BrokerOutcome(
                    terminal: .baseline(changeCount: count),
                    metrics: BrokerMetrics(
                        beforeChangeCount: count,
                        afterChangeCount: count
                    )
                )
            }
#endif
            let count = pasteboardChangeCount()
            return BrokerOutcome(
                terminal: .baseline(changeCount: count),
                metrics: BrokerMetrics(
                    beforeChangeCount: count,
                    afterChangeCount: count
                )
            )
        case .shutdown:
            return BrokerOutcome(
                terminal: .shutdown,
                metrics: BrokerMetrics(terminalStatus: "shutdown")
            )
        }
    }

    private func observe(
        _ request: ClipboardBrokerObserveRequest,
        requestID: UUID
    ) throws -> BrokerOutcome {
#if DEBUG
        if ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ] == "block_observe" {
            while true {
                usleep(250_000)
            }
        }
        let observedBefore = ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FIXED_CHANGE_COUNT"
        ].flatMap(Int.init) ?? pasteboardChangeCount()
#else
        let observedBefore = pasteboardChangeCount()
#endif
        var metrics = BrokerMetrics(
            beforeChangeCount: observedBefore,
            afterChangeCount: observedBefore
        )

        if request.baselineChangeCount == observedBefore {
            metrics.terminalStatus = "no_change"
            return observationOutcome(
                status: .noChange,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        if request.suppressedChangeCounts.contains(observedBefore) {
            metrics.terminalStatus = ClipboardBrokerSkipReason.selfWrite.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                skipReason: .selfWrite,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        if request.poisonedChangeCount == observedBefore {
            metrics.terminalStatus = ClipboardBrokerSkipReason.poisonedChange.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                skipReason: .poisonedChange,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        if request.prefilterDisposition != .allow {
            metrics.terminalStatus = "redacted"
            return observationOutcome(
                status: .redacted,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        try sendStarted(
            requestID: requestID,
            operation: .observe,
            changeCount: observedBefore
        )
#if DEBUG
        if ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ] == "block_observe_after_start" {
            while true {
                usleep(250_000)
            }
        }
#endif
        let advertisedTypes = pasteboardTypes() ?? []
        let advertisedTypeNames = advertisedTypes.map(\.rawValue).sorted()
        let advertisedTypeSet = Set(advertisedTypeNames)
        metrics.typeCount = advertisedTypeNames.count
        var advertisedTypeByteCount = 0
        for typeName in advertisedTypeNames {
            let count = typeName.utf8.count
            guard count <= ClipboardBrokerLimits.maxTextBytes - advertisedTypeByteCount else {
                metrics.terminalStatus = ClipboardBrokerSkipReason.oversized.rawValue
                return observationOutcome(
                    status: .skipped,
                    changeCount: observedBefore,
                    observedAfter: observedBefore,
                    skipReason: .oversized,
                    prefilterDisposition: request.prefilterDisposition,
                    metrics: metrics
                )
            }
            advertisedTypeByteCount += count
        }

        if !advertisedTypeSet.isDisjoint(with: PasteboardMarkers.sensitive) {
            metrics.terminalStatus = ClipboardBrokerSkipReason.sensitiveMarker.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                skipReason: .sensitiveMarker,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        if !advertisedTypeSet.isDisjoint(with: PasteboardMarkers.remote) {
            metrics.terminalStatus = ClipboardBrokerSkipReason.remoteClipboard.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                skipReason: .remoteClipboard,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        guard let selected = preferredRepresentation(in: advertisedTypes) else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.unsupported.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                skipReason: .unsupported,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        metrics.family = selected.family
        if request.screenSharingActive {
            metrics.terminalStatus = ClipboardBrokerObservationStatus.deferred.rawValue
            return observationOutcome(
                status: .deferred,
                changeCount: observedBefore,
                observedAfter: observedBefore,
                resolutionTicket: ClipboardBrokerResolutionTicket(
                    changeCount: observedBefore,
                    family: selected.family,
                    pasteboardType: selected.pasteboardType.rawValue,
                    advertisedTypes: advertisedTypeNames
                ),
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        let rawCapture = readSelectedRepresentation(selected)
        let observedAfter = pasteboardChangeCount()
        metrics.afterChangeCount = observedAfter

        guard observedAfter == observedBefore else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.stale.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedAfter,
                skipReason: .stale,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        guard let representation = try materialize(
            rawCapture,
            advertisedTypes: advertisedTypeNames,
            metrics: &metrics
        ) else {
            let reason: ClipboardBrokerSkipReason
            if metrics.terminalStatus == ClipboardBrokerSkipReason.oversized.rawValue {
                reason = .oversized
            } else {
                reason = .unsupported
                metrics.terminalStatus = reason.rawValue
            }
            return observationOutcome(
                status: .skipped,
                changeCount: observedBefore,
                observedAfter: observedAfter,
                skipReason: reason,
                prefilterDisposition: request.prefilterDisposition,
                metrics: metrics
            )
        }

        metrics.itemCount = 1
        metrics.terminalStatus = "captured"
        return BrokerOutcome(
            terminal: .observation(
                ClipboardBrokerObservationResult(
                    status: .captured,
                    changeCount: observedBefore,
                    observedAfterChangeCount: observedAfter,
                    representation: representation,
                    prefilterDisposition: request.prefilterDisposition
                )
            ),
            metrics: metrics
        )
    }

    private func resolve(
        _ request: ClipboardBrokerResolveRequest,
        requestID: UUID
    ) throws -> BrokerOutcome {
#if DEBUG
        if ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ] == "block_resolve" {
            while true {
                usleep(250_000)
            }
        }
#endif
        let ticket = request.ticket
        let observedBefore = pasteboardChangeCount()
        var metrics = BrokerMetrics(
            family: ticket.family,
            beforeChangeCount: observedBefore,
            afterChangeCount: observedBefore
        )
        guard observedBefore == ticket.changeCount else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.stale.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: ticket.changeCount,
                observedAfter: observedBefore,
                skipReason: .stale,
                prefilterDisposition: .allow,
                metrics: metrics
            )
        }
        guard let selected = selectedRepresentation(from: ticket) else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.unsupported.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: ticket.changeCount,
                observedAfter: observedBefore,
                skipReason: .unsupported,
                prefilterDisposition: .allow,
                metrics: metrics
            )
        }

        try sendStarted(
            requestID: requestID,
            operation: .resolve,
            changeCount: observedBefore
        )
        let rawCapture = readSelectedRepresentation(selected)
        let observedAfter = pasteboardChangeCount()
        metrics.afterChangeCount = observedAfter

        guard observedAfter == observedBefore else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.stale.rawValue
            return observationOutcome(
                status: .skipped,
                changeCount: ticket.changeCount,
                observedAfter: observedAfter,
                skipReason: .stale,
                prefilterDisposition: .allow,
                metrics: metrics
            )
        }
        guard let representation = try materialize(
            rawCapture,
            advertisedTypes: ticket.advertisedTypes,
            metrics: &metrics
        ) else {
            let reason: ClipboardBrokerSkipReason
            if metrics.terminalStatus == ClipboardBrokerSkipReason.oversized.rawValue {
                reason = .oversized
            } else {
                reason = .unsupported
                metrics.terminalStatus = reason.rawValue
            }
            return observationOutcome(
                status: .skipped,
                changeCount: ticket.changeCount,
                observedAfter: observedAfter,
                skipReason: reason,
                prefilterDisposition: .allow,
                metrics: metrics
            )
        }

        metrics.itemCount = 1
        metrics.terminalStatus = "captured"
        return BrokerOutcome(
            terminal: .observation(
                ClipboardBrokerObservationResult(
                    status: .captured,
                    changeCount: ticket.changeCount,
                    observedAfterChangeCount: observedAfter,
                    representation: representation
                )
            ),
            metrics: metrics
        )
    }

    private struct SelectedRepresentation {
        let family: ClipboardBrokerRepresentationFamily
        let pasteboardType: NSPasteboard.PasteboardType
    }

    private enum RawCapture {
        case string(SelectedRepresentation, String?)
        case data(SelectedRepresentation, Data?)
    }

    private func preferredRepresentation(
        in advertisedTypes: [NSPasteboard.PasteboardType]
    ) -> SelectedRepresentation? {
        let advertised = Set(advertisedTypes)
        if advertised.contains(.png) {
            return SelectedRepresentation(family: .imagePNG, pasteboardType: .png)
        }
        if advertised.contains(.tiff) {
            return SelectedRepresentation(family: .imageTIFF, pasteboardType: .tiff)
        }
        if advertised.contains(.fileURL) {
            return SelectedRepresentation(family: .fileURL, pasteboardType: .fileURL)
        }
        if advertised.contains(.URL) {
            return SelectedRepresentation(family: .url, pasteboardType: .URL)
        }
        if advertised.contains(.rtf) {
            return SelectedRepresentation(family: .richText, pasteboardType: .rtf)
        }
        if advertised.contains(.string) {
            return SelectedRepresentation(family: .text, pasteboardType: .string)
        }
        return nil
    }

    private func selectedRepresentation(
        from ticket: ClipboardBrokerResolutionTicket
    ) -> SelectedRepresentation? {
        let expectedType: NSPasteboard.PasteboardType
        switch ticket.family {
        case .fileURL:
            expectedType = .fileURL
        case .imagePNG:
            expectedType = .png
        case .imageTIFF:
            expectedType = .tiff
        case .url:
            expectedType = .URL
        case .richText:
            expectedType = .rtf
        case .text:
            expectedType = .string
        }
        guard ticket.pasteboardType == expectedType.rawValue,
              ticket.advertisedTypes.contains(ticket.pasteboardType),
              ticket.advertisedTypes.count <= 256 else {
            return nil
        }
        var advertisedTypeByteCount = 0
        for typeName in ticket.advertisedTypes {
            guard typeName.utf8.count
                    <= ClipboardBrokerLimits.maxTextBytes - advertisedTypeByteCount
            else {
                return nil
            }
            advertisedTypeByteCount += typeName.utf8.count
        }
        return SelectedRepresentation(
            family: ticket.family,
            pasteboardType: expectedType
        )
    }

    private func readSelectedRepresentation(_ selected: SelectedRepresentation) -> RawCapture {
        switch selected.family {
        case .fileURL, .url, .text:
            return .string(
                selected,
                pasteboardString(forType: selected.pasteboardType)
            )
        case .imagePNG, .imageTIFF, .richText:
            return .data(
                selected,
                pasteboardData(forType: selected.pasteboardType)
            )
        }
    }

    private func materialize(
        _ rawCapture: RawCapture,
        advertisedTypes: [String],
        metrics: inout BrokerMetrics
    ) throws -> ClipboardBrokerCapturedRepresentation? {
        switch rawCapture {
        case let .string(selected, value):
            guard let value else { return nil }
            let bytes = value.utf8.count
            guard bytes <= ClipboardBrokerLimits.maxTextBytes else {
                metrics.byteCount = bytes
                metrics.terminalStatus = ClipboardBrokerSkipReason.oversized.rawValue
                return nil
            }
            metrics.byteCount = bytes
            return ClipboardBrokerCapturedRepresentation(
                family: selected.family,
                pasteboardType: selected.pasteboardType.rawValue,
                advertisedTypes: advertisedTypes,
                value: value,
                plainText: selected.family == .text ? value : nil
            )

        case let .data(selected, data):
            guard let data else { return nil }
            let byteCount = data.count
            metrics.byteCount = byteCount
            let limit: Int
            switch selected.family {
            case .imagePNG:
                limit = ClipboardBrokerLimits.maxCanonicalPNGBytes
            case .imageTIFF:
                limit = ClipboardBrokerLimits.maxRawImageBytes
            case .richText:
                limit = ClipboardBrokerLimits.maxRTFBytes
            case .fileURL, .url, .text:
                throw BrokerFailure.invalidRequest
            }
            guard byteCount <= limit else {
                metrics.terminalStatus = ClipboardBrokerSkipReason.oversized.rawValue
                return nil
            }

            let plainText: String?
            if selected.family == .richText {
                let derivedText = (try? NSAttributedString(
                    data: data,
                    options: [.documentType: NSAttributedString.DocumentType.rtf],
                    documentAttributes: nil
                ))?.string
                plainText = derivedText.map {
                    boundedUTF8String(
                        $0,
                        maximumByteCount: ClipboardBrokerLimits.maxTextBytes
                    )
                }
            } else {
                plainText = nil
            }

            let transportedData: Data
            if selected.family == .imageTIFF {
                guard let bitmap = NSBitmapImageRep(data: data),
                      let canonicalPNG = bitmap.representation(
                          using: .png,
                          properties: [:]
                      ),
                      canonicalPNG.count <= ClipboardBrokerLimits.maxCanonicalPNGBytes else {
                    metrics.terminalStatus = ClipboardBrokerSkipReason.oversized.rawValue
                    return nil
                }
                transportedData = canonicalPNG
                metrics.byteCount = canonicalPNG.count
            } else {
                transportedData = data
            }

            let dataReference: ClipboardBrokerDataReference
            if selected.family == .imagePNG || selected.family == .imageTIFF,
               transportedData.count > ClipboardBrokerLimits.inlineImageBytes {
                dataReference = try stagingStore.stage(transportedData)
            } else {
                dataReference = .inline(transportedData)
            }
            return ClipboardBrokerCapturedRepresentation(
                family: selected.family,
                pasteboardType: selected.pasteboardType.rawValue,
                advertisedTypes: advertisedTypes,
                plainText: plainText,
                data: dataReference
            )
        }
    }

    private func materializeWrite(
        _ request: ClipboardBrokerWriteRequest
    ) throws -> MaterializedWrite {
        guard !request.items.isEmpty,
              request.items.count <= 64 else {
            throw BrokerFailure.invalidRequest
        }

        var pasteboardItems: [NSPasteboardWriting] = []
        pasteboardItems.reserveCapacity(request.items.count)
        var semanticFileURLs: [URL] = []
        var semanticFileItemIndices: [Int] = []
        var expectedRepresentations: [Int: [PostWriteRepresentation]] = [:]
        var representationCount = 0
        var byteCount = 0
        func addByteCount(_ count: Int) throws {
            guard count >= 0,
                  count <= ClipboardBrokerLimits.maxFrameBytes - byteCount else {
                throw BrokerFailure.oversized
            }
            byteCount += count
        }

        for writeItem in request.items {
            if let semanticFileURLString = writeItem.semanticFileURLString {
                guard writeItem.representations.isEmpty,
                      semanticFileURLString.utf8.count
                        <= ClipboardBrokerLimits.maxTextBytes,
                      let fileURL = URL(string: semanticFileURLString),
                      fileURL.isFileURL else {
                    throw BrokerFailure.invalidRequest
                }
                try addByteCount(semanticFileURLString.utf8.count)
                semanticFileItemIndices.append(pasteboardItems.count)
                pasteboardItems.append(fileURL as NSURL)
                semanticFileURLs.append(fileURL)
                representationCount += 1
                guard representationCount <= 256 else {
                    throw BrokerFailure.invalidRequest
                }
                continue
            }
            guard !writeItem.representations.isEmpty else {
                throw BrokerFailure.invalidRequest
            }
            var seenTypes = Set<String>()
            var sourcePNGData: Data?
            let pasteboardItem = NSPasteboardItem()
            var expectedItemRepresentations: [PostWriteRepresentation] = []
            for entry in writeItem.representations {
                guard !entry.pasteboardType.isEmpty,
                      seenTypes.insert(entry.pasteboardType).inserted else {
                    throw BrokerFailure.invalidRequest
                }
                let type = NSPasteboard.PasteboardType(entry.pasteboardType)
                let wroteRepresentation: Bool
                switch entry.value {
                case let .string(value):
                    let bytes = value.utf8.count
                    guard bytes <= stringLimit(for: type) else {
                        throw BrokerFailure.oversized
                    }
                    try addByteCount(bytes)
                    wroteRepresentation = pasteboardItem.setString(value, forType: type)

                case let .data(reference):
                    let data = try stagingStore.load(reference)
                    guard data.count <= dataLimit(for: type) else {
                        throw BrokerFailure.oversized
                    }
                    try addByteCount(data.count)
                    wroteRepresentation = pasteboardItem.setData(data, forType: type)
                    if type == .png {
                        sourcePNGData = data
                    }

                case let .stringList(values):
                    var bytes = 0
                    for value in values {
                        let count = value.utf8.count
                        guard count <= ClipboardBrokerLimits.maxTextBytes - bytes else {
                            throw BrokerFailure.oversized
                        }
                        bytes += count
                    }
                    guard bytes <= ClipboardBrokerLimits.maxTextBytes else {
                        throw BrokerFailure.oversized
                    }
                    try addByteCount(bytes)
                    wroteRepresentation = pasteboardItem.setPropertyList(values, forType: type)
                }
                guard wroteRepresentation else {
                    throw BrokerFailure.invalidRequest
                }
                guard let expectedData = pasteboardItem.data(forType: type) else {
                    throw BrokerFailure.invalidRequest
                }
                expectedItemRepresentations.append(PostWriteRepresentation(
                    type: type,
                    data: expectedData
                ))
                representationCount += 1
                guard representationCount <= 256 else {
                    throw BrokerFailure.invalidRequest
                }
            }

            // Compatibility TIFF is derived only inside the recoverable Broker.
            // A malformed or expensive image can therefore never block the App
            // process, and failure to derive TIFF does not discard a valid PNG.
            if !seenTypes.contains(NSPasteboard.PasteboardType.tiff.rawValue),
               let sourcePNGData,
               let bitmap = NSBitmapImageRep(data: sourcePNGData),
               let derivedTIFF = bitmap.representation(
                   using: .tiff,
                   properties: [:]
               ),
               derivedTIFF.count <= ClipboardBrokerLimits.maxRawImageBytes,
               derivedTIFF.count <= ClipboardBrokerLimits.maxFrameBytes - byteCount,
               pasteboardItem.setData(derivedTIFF, forType: .tiff) {
                try addByteCount(derivedTIFF.count)
                expectedItemRepresentations.append(PostWriteRepresentation(
                    type: .tiff,
                    data: derivedTIFF
                ))
                representationCount += 1
                guard representationCount <= 256 else {
                    throw BrokerFailure.invalidRequest
                }
            }
            expectedRepresentations[pasteboardItems.count] = expectedItemRepresentations
            pasteboardItems.append(pasteboardItem)
        }

        return MaterializedWrite(
            pasteboardItems: pasteboardItems,
            itemCount: pasteboardItems.count,
            representationCount: representationCount,
            byteCount: byteCount,
            semanticFileURLs: semanticFileURLs,
            semanticFileItemIndices: semanticFileItemIndices,
            expectedRepresentations: expectedRepresentations
        )
    }

    private func write(
        _ request: ClipboardBrokerWriteRequest,
        requestID: UUID
    ) throws -> BrokerOutcome {
        let materialized = try materializeWrite(request)
        return try performMaterializedWrite(
            materialized,
            expectedChangeCount: request.expectedChangeCount,
            requestID: requestID,
            operation: .write
        )
    }

    private func prepareWrite(
        _ request: ClipboardBrokerPrepareWriteRequest
    ) throws -> BrokerOutcome {
        pruneExpiredPreparedWrites()
        guard preparedWrites.count < Self.maximumPreparedWrites else {
            throw BrokerFailure.invalidRequest
        }
        let materialized = try materializeWrite(request.write)
        let capturedChangeCount = pasteboardChangeCount()
        let expectedChangeCount = request.write.expectedChangeCount
        let preparedWriteID = UUID()
        let expiresAtSystemUptime = ProcessInfo.processInfo.systemUptime
            + Self.preparedWriteLifetime
        preparedWrites[preparedWriteID] = PreparedWrite(
            materialized: materialized,
            expectedChangeCount: expectedChangeCount,
            capturedChangeCount: capturedChangeCount,
            expiresAtSystemUptime: expiresAtSystemUptime
        )
        return BrokerOutcome(
            terminal: .preparedWrite(ClipboardBrokerPreparedWriteResult(
                preparedWriteID: preparedWriteID,
                itemCount: materialized.itemCount,
                representationCount: materialized.representationCount,
                expiresAtSystemUptime: expiresAtSystemUptime
            )),
            metrics: BrokerMetrics(
                itemCount: materialized.itemCount,
                typeCount: materialized.representationCount,
                byteCount: materialized.byteCount,
                terminalStatus: "prepared"
            )
        )
    }

    private func commitWrite(
        _ request: ClipboardBrokerCommitWriteRequest,
        requestID: UUID
    ) throws -> BrokerOutcome {
        pruneExpiredPreparedWrites()
        // Removal is the serialized linearization point: a later commit or
        // cancel observes an unknown ID and cannot cause another write.
        guard let prepared = preparedWrites.removeValue(
            forKey: request.preparedWriteID
        ) else {
            throw BrokerFailure.invalidRequest
        }
        let actualBefore = pasteboardChangeCount()
        guard actualBefore == prepared.capturedChangeCount,
              prepared.expectedChangeCount.map({
                  $0 == prepared.capturedChangeCount
              }) ?? true else {
            return changedWriteOutcome(
                materialized: prepared.materialized,
                changeCount: actualBefore
            )
        }
        return try performMaterializedWrite(
            prepared.materialized,
            expectedChangeCount: prepared.capturedChangeCount,
            requestID: requestID,
            operation: .commitWrite
        )
    }

    private func cancelWrite(
        _ request: ClipboardBrokerCancelWriteRequest
    ) throws -> BrokerOutcome {
        pruneExpiredPreparedWrites()
        // As with commit, removeValue makes cancellation single-use and
        // fail-closed for duplicate or unknown IDs.
        guard preparedWrites.removeValue(forKey: request.preparedWriteID) != nil else {
            throw BrokerFailure.invalidRequest
        }
        return BrokerOutcome(
            terminal: .cancelledWrite(preparedWriteID: request.preparedWriteID),
            metrics: BrokerMetrics(terminalStatus: "cancelled")
        )
    }

    private func pruneExpiredPreparedWrites(
        systemUptime: TimeInterval = ProcessInfo.processInfo.systemUptime
    ) {
        preparedWrites = preparedWrites.filter { _, prepared in
            prepared.expiresAtSystemUptime > systemUptime
        }
    }

    private func performMaterializedWrite(
        _ materialized: MaterializedWrite,
        expectedChangeCount: Int?,
        requestID: UUID,
        operation: ClipboardBrokerOperation
    ) throws -> BrokerOutcome {
        let actualBefore = pasteboardChangeCount()
        if let expected = expectedChangeCount,
           expected != actualBefore {
            return changedWriteOutcome(
                materialized: materialized,
                changeCount: actualBefore
            )
        }

        try sendStarted(
            requestID: requestID,
            operation: operation,
            changeCount: actualBefore
        )
        guard semanticFileURLsAreRestorable(materialized.semanticFileURLs) else {
            return BrokerOutcome(
                terminal: .write(
                    ClipboardBrokerWriteResult(
                        status: .failed,
                        beforeChangeCount: actualBefore,
                        afterChangeCount: actualBefore,
                        changedCounts: [],
                        itemCount: materialized.itemCount,
                        representationCount: materialized.representationCount
                    )
                ),
                metrics: BrokerMetrics(
                    itemCount: materialized.itemCount,
                    typeCount: materialized.representationCount,
                    byteCount: materialized.byteCount,
                    beforeChangeCount: actualBefore,
                    afterChangeCount: actualBefore,
                    terminalStatus: "failed_file_url_unavailable"
                )
            )
        }
#if DEBUG
        pauseBeforeClearIfRequested()
#endif
        // `clearContents` has no compare-and-swap form. Re-read immediately
        // before it so a publisher that arrived after the expected-count
        // check remains observable instead of being destructively cleared.
        let actualBeforeClear = pasteboardChangeCount()
        guard actualBeforeClear == actualBefore else {
            return changedWriteOutcome(
                materialized: materialized,
                beforeChangeCount: actualBefore,
                afterChangeCount: actualBeforeClear,
                changedCounts: []
            )
        }
        let afterClear = clearPasteboard()
#if DEBUG
        if operation == .commitWrite {
            switch ProcessInfo.processInfo.environment[
                "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
            ] {
            case "delay_commit_write_after_clear":
                usleep(250_000)
            case "delay_commit_write_after_clear_past_request_timeout":
                usleep(1_250_000)
            case "hang_commit_write_after_clear":
                while true {
                    _ = Darwin.pause()
                }
            default:
                break
            }
        }
#endif
        // Fence clear -> native write. If another publisher appears between
        // them, do not replace it and do not attempt recovery over it.
        guard pasteboardChangeCount() == afterClear else {
            return changedWriteOutcome(
                materialized: materialized,
                beforeChangeCount: actualBefore,
                afterChangeCount: pasteboardChangeCount(),
                changedCounts: [afterClear]
            )
        }
        let targetPublication = writeMaterializedPasteboard(
            materialized,
            purpose: .target,
            lastClearedChangeCount: afterClear
        )
#if DEBUG
        let targetWriteFault = ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ]
        if targetWriteFault == "pause_after_target_write" {
            usleep(500_000)
        } else if targetWriteFault == "pause_before_rollback_final_fence",
                  let writtenItem = pasteboard.pasteboardItems?.first {
            _ = writtenItem.setString(
                "mismatched target",
                forType: .string
            )
            // Kept only as a deterministic test seam: recovery is disabled,
            // so an external publication here must remain untouched.
            usleep(500_000)
        } else if targetWriteFault
            == "target_write_returns_true_but_semantic_file_unreadable",
            let itemIndex = materialized.semanticFileItemIndices.first,
            let writtenItems = pasteboard.pasteboardItems,
            writtenItems.indices.contains(itemIndex) {
            _ = writtenItems[itemIndex].setString(
                "https://example.invalid/not-a-file",
                forType: .fileURL
            )
        } else if targetWriteFault
            == "target_write_returns_true_but_representation_mismatched",
            let itemIndex = materialized.expectedRepresentations.keys.sorted().first,
            let representation = materialized.expectedRepresentations[itemIndex]?.first,
            let writtenItems = pasteboard.pasteboardItems,
            writtenItems.indices.contains(itemIndex) {
            // Simulate an AppKit publication that reports success and keeps the
            // same change count while exposing bytes other than the bounded
            // representation we supplied. The verifier, not this fixture,
            // must detect the mismatch.
            _ = writtenItems[itemIndex].setData(
                Data([0x00]),
                forType: representation.type
            )
        }
#endif
        let targetVerification: PasteboardPublicationVerification
        switch targetPublication {
        case let .published(changeCount):
            targetVerification = verifyMaterializedPasteboard(
                materialized,
                expectedChangeCount: changeCount,
                purpose: .target
            )
        case .changed, .changedBeforePostWriteFence:
            targetVerification = .changed
        case .failed:
            // A false return has no ownership token. Only the clear count is
            // known to be ours; a later count can already be an external
            // publisher and must not be adopted as a self-write.
            targetVerification = pasteboardChangeCount() == afterClear
                ? .mismatched
                : .changed
        }

        // A same-count representation mismatch is not an ownership proof:
        // AppKit or another publisher may have replaced bytes without giving
        // the Broker a distinguishable token. Treat it as changed unless the
        // native write itself definitively returned false while the clear
        // count is still current.
        let definitiveTargetFailure: Bool
        if case .failed = targetPublication,
           targetVerification == .mismatched {
            definitiveTargetFailure = true
        } else {
            definitiveTargetFailure = false
        }

#if DEBUG
        if ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ] == "target_verified_then_external_replaces_before_terminal_sample" {
            let sentinel = NSPasteboardItem()
            _ = sentinel.setString("external sentinel", forType: .string)
            pasteboard.clearContents()
            _ = pasteboard.writeObjects([sentinel])
        }
#endif

        let actualAfter = pasteboardChangeCount()
        let verifiedTargetChangeCount: Int? = if targetVerification == .verified,
            case let .published(publishedTargetChangeCount) = targetPublication,
            actualAfter == publishedTargetChangeCount {
            publishedTargetChangeCount
        } else {
            nil
        }
        var confirmedChangedCounts: [Int] = []
        if let verifiedTargetChangeCount {
            confirmedChangedCounts.append(afterClear)
            confirmedChangedCounts.append(verifiedTargetChangeCount)
        }
        // NSPasteboard has no cross-process compare-and-swap. Once clear or a
        // target publication has happened, no final count fence can make a
        // destructive rollback safe: another app can publish immediately
        // before the rollback clear/write. A system write failure can therefore
        // leave the original clipboard empty or partially target-written; that
        // loss is preferable to overwriting a newer external publisher.
        let changedCounts = confirmedChangedCounts.reduce(into: [Int]()) {
            if !$0.contains($1) {
                $0.append($1)
            }
        }
        let status: ClipboardBrokerWriteStatus
        switch (targetVerification, verifiedTargetChangeCount, definitiveTargetFailure) {
        case (.verified, .some, _):
            status = .succeeded
        case (.mismatched, _, true):
            status = .failed
        case (.changed, _, _), (.verified, .none, _), (.mismatched, _, false):
            status = .changed
        }
        let terminalStatus: String
        if status == .succeeded {
            terminalStatus = status.rawValue
        } else if status == .changed {
            terminalStatus = "changed"
        } else {
            terminalStatus = "failed_target_write_not_restored"
        }
        return BrokerOutcome(
            terminal: .write(
                ClipboardBrokerWriteResult(
                    status: status,
                    beforeChangeCount: actualBefore,
                    afterChangeCount: actualAfter,
                    changedCounts: changedCounts,
                    itemCount: materialized.itemCount,
                    representationCount: materialized.representationCount
                )
            ),
            metrics: BrokerMetrics(
                itemCount: materialized.itemCount,
                typeCount: materialized.representationCount,
                byteCount: materialized.byteCount,
                beforeChangeCount: actualBefore,
                afterChangeCount: actualAfter,
                terminalStatus: terminalStatus
            )
        )
    }

