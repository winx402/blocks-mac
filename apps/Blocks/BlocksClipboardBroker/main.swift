    private func writePasteboardObjects(
        _ items: [NSPasteboardWriting],
        purpose: PasteboardWritePurpose = .target
    ) -> Bool {
#if DEBUG
        testInstrumentation.recordWrite()
        let fault = ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ]
        if purpose == .target,
           fault == "target_fails_and_external_replaces_compound_before_native_write_change_count" {
            _ = pasteboard.writeObjects(items)
            let sentinel = NSPasteboardItem()
            _ = sentinel.setString("external sentinel", forType: .string)
            pasteboard.clearContents()
            _ = pasteboard.writeObjects([sentinel])
            return false
        }
        let injectedFailure = (purpose == .target
            && (fault == "fail_write_after_clear"
                || fault == "fail_write_and_rollback_after_clear"
                || fault == "target_fails_and_external_replaces_compound_rollback"
                || fault == "target_fails_and_external_replaces_compound_before_native_write_change_count"
                || fault == "target_write_returns_false_and_rollback_verification_fails"))
            || (purpose == .rollback
                && fault == "fail_write_and_rollback_after_clear")
        return !injectedFailure && pasteboard.writeObjects(items)
#else
        return pasteboard.writeObjects(items)
#endif
    }

    private func writeMaterializedPasteboard(
        _ materialized: MaterializedWrite,
        purpose: PasteboardWritePurpose,
        lastClearedChangeCount: Int
    ) -> MaterializedPasteboardWriteResult {
        guard semanticFileURLsAreRestorable(materialized.semanticFileURLs) else {
            return .failed
        }
        let nativeWriteSucceeded = writePasteboardObjects(
            materialized.pasteboardItems,
            purpose: purpose
        )
#if DEBUG
        let injectedPartialFailure = purpose == .target
            && ProcessInfo.processInfo.environment[
                "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
            ] == "partial_write_then_fail_after_clear"
        if injectedPartialFailure {
            // Model a native API that exposed a bounded partial item before
            // returning false. The clear is part of this deterministic fault,
            // not a recovery attempt over a newer publisher.
            pasteboard.clearContents()
            _ = pasteboard.setString(
                "partial replacement",
                forType: .string
            )
        }
#else
        let injectedPartialFailure = false
#endif
        let nativeWriteChangeCount = pasteboardChangeCount()
        guard nativeWriteSucceeded, !injectedPartialFailure else {
            // `NSPasteboard.writeObjects` may return false after publishing a
            // partial target. A change-count movement beyond our preceding
            // clear is therefore ambiguous ownership, never a definitive
            // failed/no-publication result.
            return !injectedPartialFailure
                && nativeWriteChangeCount == lastClearedChangeCount
                ? .failed
                : .changed
        }
#if DEBUG
        if purpose == .target,
           ProcessInfo.processInfo.environment[
               "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
           ] == "target_write_succeeds_then_external_replaces_before_native_write_change_count" {
            // Deliberately replace the target in the only unobservable window
            // between `writeObjects` returning and the first ownership sample.
            // The normal verifier must fail safe without rolling this out-of-
            // process sentinel back.
            let sentinel = NSPasteboardItem()
            _ = sentinel.setString("external sentinel", forType: .string)
            pasteboard.clearContents()
            _ = pasteboard.writeObjects([sentinel])
        }
#endif
        guard !materialized.postWriteRepresentations.isEmpty else {
            return .published(changeCount: nativeWriteChangeCount)
        }
#if DEBUG
        if purpose == .rollback,
           ProcessInfo.processInfo.environment[
               "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
           ] == "target_fails_and_external_replaces_compound_rollback" {
            let sentinel = NSPasteboardItem()
            _ = sentinel.setString("external sentinel", forType: .string)
            pasteboard.clearContents()
            _ = pasteboard.writeObjects([sentinel])
        }
#endif
        // `pasteboardItems` is mutable shared state. Do not attach compound
        // PNG/TIFF data unless the native NSURL publication is still current.
        guard pasteboardChangeCount() == nativeWriteChangeCount,
              let writtenItems = pasteboard.pasteboardItems,
              writtenItems.count == materialized.itemCount else {
            return .changed
        }
        guard nativeFileURLIdentitiesMatch(
            materialized,
            writtenItems: writtenItems
        ) else {
            return .changedBeforePostWriteFence
        }
        for (itemIndex, representations) in materialized.postWriteRepresentations {
            guard pasteboardChangeCount() == nativeWriteChangeCount,
                  writtenItems.indices.contains(itemIndex) else {
                return .changed
            }
            for representation in representations {
                guard pasteboardChangeCount() == nativeWriteChangeCount else {
                    return .changed
                }
                guard writtenItems[itemIndex].setData(
                    representation.data,
                    forType: representation.type
                ) else {
                    return .failed
                }
            }
        }
        return pasteboardChangeCount() == nativeWriteChangeCount
            ? .published(changeCount: nativeWriteChangeCount)
            : .changed
    }

    /// Verifies only the bounded representations the Broker itself published.
    /// The change-count checks fence both sides of the reads so a concurrent
    /// publisher is classified as `.changed`, never as a failed Broker write.
    private func verifyMaterializedPasteboard(
        _ materialized: MaterializedWrite,
        expectedChangeCount: Int,
        purpose: PasteboardWritePurpose
    ) -> PasteboardPublicationVerification {
        guard pasteboardChangeCount() == expectedChangeCount else {
            return .changed
        }

        var matches = true
        let writtenItems = pasteboard.pasteboardItems ?? []
        matches = writtenItems.count == materialized.itemCount

        if matches {
            matches = nativeFileURLIdentitiesMatch(
                materialized,
                writtenItems: writtenItems
            )
        }

        if matches, !materialized.semanticFileURLs.isEmpty {
            let publishedURLs = pasteboard.readObjects(
                forClasses: [NSURL.self]
            ) as? [URL]
            matches = publishedURLs?.map(\.standardizedFileURL)
                == materialized.semanticFileURLs.map(\.standardizedFileURL)
        }

        if matches {
            for (itemIndex, representations) in materialized.expectedRepresentations {
                guard writtenItems.indices.contains(itemIndex) else {
                    matches = false
                    break
                }
                for representation in representations where writtenItems[itemIndex].data(
                    forType: representation.type
                ) != representation.data {
                    matches = false
                    break
                }
                if !matches { break }
            }
        }

#if DEBUG
        let fault = ProcessInfo.processInfo.environment[
            "BLOCKS_CLIPBOARD_BROKER_TEST_FAULT"
        ]
        if purpose == .rollback
                && (fault == "rollback_write_returns_true_but_verification_fails"
                    || fault == "target_write_returns_false_and_rollback_verification_fails") {
            matches = false
        }
#endif

        return pasteboardChangeCount() == expectedChangeCount
            ? (matches ? .verified : .mismatched)
            : .changed
    }

    private func standardizedFileURL(_ rawValue: String) -> URL? {
        guard let url = URL(string: rawValue), url.isFileURL else {
            return nil
        }
        return url.standardizedFileURL
    }

    private func nativeFileURLIdentitiesMatch(
        _ materialized: MaterializedWrite,
        writtenItems: [NSPasteboardItem]
    ) -> Bool {
        guard materialized.semanticFileItemIndices.count
                == materialized.semanticFileURLs.count else {
            return false
        }
        for (itemIndex, expectedURL) in zip(
            materialized.semanticFileItemIndices,
            materialized.semanticFileURLs
        ) {
            guard writtenItems.indices.contains(itemIndex),
                  let rawURL = pasteboardItemString(
                      writtenItems[itemIndex],
                      forType: .fileURL
                  ),
                  standardizedFileURL(rawURL) == expectedURL.standardizedFileURL else {
                return false
            }
        }
        return true
    }

    private func observationOutcome(
        status: ClipboardBrokerObservationStatus,
        changeCount: Int,
        observedAfter: Int,
        resolutionTicket: ClipboardBrokerResolutionTicket? = nil,
        skipReason: ClipboardBrokerSkipReason? = nil,
        prefilterDisposition: ClipboardBrokerPrefilterDisposition,
        metrics: BrokerMetrics
    ) -> BrokerOutcome {
        BrokerOutcome(
            terminal: .observation(
                ClipboardBrokerObservationResult(
                    status: status,
                    changeCount: changeCount,
                    observedAfterChangeCount: observedAfter,
                    resolutionTicket: resolutionTicket,
                    skipReason: skipReason,
                    prefilterDisposition: prefilterDisposition
                )
            ),
            metrics: metrics
        )
    }

    private func stringLimit(for type: NSPasteboard.PasteboardType) -> Int {
        if type == .rtf {
            return ClipboardBrokerLimits.maxRTFBytes
        }
        return ClipboardBrokerLimits.maxTextBytes
    }

    private func dataLimit(for type: NSPasteboard.PasteboardType) -> Int {
        if type == .png {
            return ClipboardBrokerLimits.maxCanonicalPNGBytes
        }
        if type == .tiff {
            return ClipboardBrokerLimits.maxRawImageBytes
        }
        if type == .rtf {
            return ClipboardBrokerLimits.maxRTFBytes
        }
        return ClipboardBrokerLimits.maxFrameBytes
    }

    private func boundedUTF8String(
        _ value: String,
        maximumByteCount: Int
    ) -> String {
        guard value.utf8.count > maximumByteCount else { return value }
        return String(decoding: value.utf8.prefix(maximumByteCount), as: UTF8.self)
    }

    private func failureOutcome(code: String) -> BrokerOutcome {
        BrokerOutcome(
            terminal: .failure(code: code),
            metrics: BrokerMetrics(terminalStatus: "failed_\(code)")
        )
    }

    private func failureCode(for error: BrokerFailure) -> String {
        switch error {
        case .invalidRequest:
            return "invalid_request"
        case .oversized:
            return "oversized"
        case .rollbackSnapshotUnavailable:
            return "rollback_snapshot_unavailable"
        case .stagingUnavailable:
            return "staging_unavailable"
        case .stagingReferenceInvalid:
            return "staging_reference_invalid"
        case .stagingWriteFailed:
            return "staging_write_failed"
        }
    }

    private func changedCounts(after original: Int, through final: Int) -> [Int] {
        guard final > original else { return [] }
        let lower = max(original + 1, final - 23)
        return Array(lower...final)
    }

    private func sendStarted(
        requestID: UUID,
        operation: ClipboardBrokerOperation,
        changeCount: Int?
    ) throws {
        try send(ClipboardBrokerResponseEnvelope(
            requestID: requestID,
            event: .started(operation: operation, changeCount: changeCount)
        ))
    }

    private func send(_ response: ClipboardBrokerResponseEnvelope) throws {
        let frame = try ClipboardBrokerFrameCodec.frame(response)
        try output.write(contentsOf: frame)
    }

    private func logTerminal(
        requestID: UUID,
        operation: ClipboardBrokerOperation,
        startedAt: UInt64,
        metrics: BrokerMetrics
    ) {
        let now = DispatchTime.now().uptimeNanoseconds
        let elapsedMilliseconds = Double(now - startedAt) / 1_000_000
        let family = metrics.family?.rawValue ?? "none"
        let before = metrics.beforeChangeCount ?? -1
        let after = metrics.afterChangeCount ?? -1
        let elapsed = String(format: "%.2f", elapsedMilliseconds)
        let message = "request_terminal id=\(requestID.uuidString) operation=\(operation.rawValue) status=\(metrics.terminalStatus) family=\(family) item_count=\(metrics.itemCount) type_count=\(metrics.typeCount) byte_count=\(metrics.byteCount) before_change_count=\(before) after_change_count=\(after) elapsed_ms=\(elapsed)"
        if metrics.terminalStatus.hasPrefix("failed_") {
            clipboardBrokerLogger.error("\(message, privacy: .public)")
        } else if operation == .observe
            && metrics.terminalStatus == ClipboardBrokerObservationStatus.noChange.rawValue {
            clipboardBrokerLogger.debug("\(message, privacy: .public)")
        } else {
            clipboardBrokerLogger.info("\(message, privacy: .public)")
        }
    }
}

