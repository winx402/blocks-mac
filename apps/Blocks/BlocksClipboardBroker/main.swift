    private func currentPlainText(
        _ request: ClipboardBrokerPlainTextRequest,
        requestID: UUID
    ) throws -> BrokerOutcome {
        let observedBefore = pasteboardChangeCount()
        try sendStarted(
            requestID: requestID,
            operation: .currentPlainText,
            changeCount: observedBefore
        )
        let advertisedTypes = pasteboardTypes() ?? []
        let advertisedTypeNames = Set(advertisedTypes.map(\.rawValue))
        var metrics = BrokerMetrics(
            family: .text,
            typeCount: advertisedTypeNames.count,
            beforeChangeCount: observedBefore,
            afterChangeCount: observedBefore
        )

        guard advertisedTypeNames.isDisjoint(with: PasteboardMarkers.sensitive),
              advertisedTypeNames.isDisjoint(with: PasteboardMarkers.remote),
              advertisedTypes.contains(.string),
              let text = pasteboardString(forType: .string) else {
            metrics.terminalStatus = "unavailable"
            return BrokerOutcome(
                terminal: .plainText(
                    ClipboardBrokerPlainTextResult(
                        text: nil,
                        originalCharacterCount: 0,
                        truncated: false,
                        changeCount: observedBefore
                    )
                ),
                metrics: metrics
            )
        }

        let observedAfter = pasteboardChangeCount()
        metrics.afterChangeCount = observedAfter
        guard observedAfter == observedBefore else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.stale.rawValue
            return BrokerOutcome(
                terminal: .plainText(
                    ClipboardBrokerPlainTextResult(
                        text: nil,
                        originalCharacterCount: 0,
                        truncated: false,
                        changeCount: observedAfter
                    )
                ),
                metrics: metrics
            )
        }

        let originalCharacterCount = text.count
        let byteCount = text.utf8.count
        metrics.byteCount = byteCount
        guard byteCount <= ClipboardBrokerLimits.maxTextBytes else {
            metrics.terminalStatus = ClipboardBrokerSkipReason.oversized.rawValue
            return BrokerOutcome(
                terminal: .plainText(
                    ClipboardBrokerPlainTextResult(
                        text: nil,
                        originalCharacterCount: originalCharacterCount,
                        truncated: true,
                        changeCount: observedAfter
                    )
                ),
                metrics: metrics
            )
        }

        let truncated = originalCharacterCount > request.maximumCharacterCount
        let resultText = truncated
            ? String(text.prefix(request.maximumCharacterCount))
            : text
        metrics.terminalStatus = truncated ? "truncated" : "completed"
        return BrokerOutcome(
            terminal: .plainText(
                ClipboardBrokerPlainTextResult(
                    text: resultText,
                    originalCharacterCount: originalCharacterCount,
                    truncated: truncated,
                    changeCount: observedAfter
                )
            ),
            metrics: metrics
        )
    }

    private func snapshot(
        _: ClipboardBrokerSnapshotRequest,
        requestID: UUID
    ) throws -> BrokerOutcome {
        let observedBefore = pasteboardChangeCount()
        try sendStarted(
            requestID: requestID,
            operation: .snapshot,
            changeCount: observedBefore
        )
        let sourceItems = pasteboard.pasteboardItems ?? []
        var metrics = BrokerMetrics(
            itemCount: sourceItems.count,
            beforeChangeCount: observedBefore,
            afterChangeCount: observedBefore
        )
        var resultItems: [ClipboardBrokerWriteItem] = []
        var unsupportedTypes: Set<String> = []
        var totalBytes = 0
        var typeCount = 0

        guard sourceItems.count <= 64 else {
            metrics.terminalStatus =
                ClipboardBrokerSnapshotStatus.oversized.rawValue
            return snapshotOutcome(
                status: .oversized,
                changeCount: observedBefore,
                metrics: metrics
            )
        }

        // Inspect every declaration before asking a provider for any value.
        // A sensitive or remote marker makes the whole snapshot ineligible:
        // reading an otherwise innocuous sibling representation first would
        // still disclose protected clipboard content.
        for sourceItem in sourceItems {
            for type in sourceItem.types {
                typeCount += 1
                guard typeCount <= 256 else {
                    metrics.typeCount = typeCount
                    metrics.terminalStatus =
                        ClipboardBrokerSnapshotStatus.oversized.rawValue
                    return snapshotOutcome(
                        status: .oversized,
                        changeCount: observedBefore,
                        metrics: metrics
                    )
                }
                let typeName = type.rawValue
                if PasteboardMarkers.sensitive.contains(typeName)
                    || PasteboardMarkers.remote.contains(typeName) {
                    unsupportedTypes.insert(typeName)
                }
            }
        }
        metrics.typeCount = typeCount
        guard unsupportedTypes.isEmpty else {
            metrics.terminalStatus =
                ClipboardBrokerSnapshotStatus.unsupported.rawValue
            return snapshotOutcome(
                status: .unsupported,
                changeCount: observedBefore,
                unsupportedTypes: Array(unsupportedTypes),
                metrics: metrics
            )
        }

        typeCount = 0
        for sourceItem in sourceItems {
            var entries: [ClipboardBrokerWriteRepresentationEntry] = []
            for type in sourceItem.types {
                let typeName = type.rawValue
                typeCount += 1

                let value: ClipboardBrokerWriteRepresentation?
                if type == .string,
                   let string = sourceItem.string(forType: type) {
                    let byteCount = string.utf8.count
                    guard byteCount <= ClipboardBrokerLimits.maxTextBytes,
                          byteCount <=
                            ClipboardBrokerLimits.maxFrameBytes
                                - totalBytes else {
                        metrics.terminalStatus =
                            ClipboardBrokerSnapshotStatus.oversized.rawValue
                        return snapshotOutcome(
                            status: .oversized,
                            changeCount: observedBefore,
                            metrics: metrics
                        )
                    }
                    totalBytes += byteCount
                    value = .string(string)
                } else if let data = sourceItem.data(forType: type) {
                    guard data.count <= dataLimit(for: type),
                          data.count <=
                            ClipboardBrokerLimits.maxFrameBytes
                                - totalBytes else {
                        metrics.terminalStatus =
                            ClipboardBrokerSnapshotStatus.oversized.rawValue
                        return snapshotOutcome(
                            status: .oversized,
                            changeCount: observedBefore,
                            metrics: metrics
                        )
                    }
                    totalBytes += data.count
                    value = .data(.inline(data))
                } else {
                    value = nil
                }
                guard let value else {
                    unsupportedTypes.insert(typeName)
                    continue
                }
                entries.append(
                    ClipboardBrokerWriteRepresentationEntry(
                        pasteboardType: typeName,
                        value: value
                    )
                )
            }
            resultItems.append(
                ClipboardBrokerWriteItem(representations: entries)
            )
        }

        let observedAfter = pasteboardChangeCount()
        metrics.afterChangeCount = observedAfter
        metrics.typeCount = typeCount
        metrics.byteCount = totalBytes
        guard observedAfter == observedBefore else {
            metrics.terminalStatus =
                ClipboardBrokerSnapshotStatus.stale.rawValue
            return snapshotOutcome(
                status: .stale,
                changeCount: observedAfter,
                metrics: metrics
            )
        }
        guard unsupportedTypes.isEmpty else {
            metrics.terminalStatus =
                ClipboardBrokerSnapshotStatus.unsupported.rawValue
            return snapshotOutcome(
                status: .unsupported,
                changeCount: observedBefore,
                unsupportedTypes: Array(unsupportedTypes),
                metrics: metrics
            )
        }
        metrics.terminalStatus =
            ClipboardBrokerSnapshotStatus.captured.rawValue
        return BrokerOutcome(
            terminal: .snapshot(
                ClipboardBrokerSnapshotResult(
                    status: .captured,
                    changeCount: observedBefore,
                    items: resultItems
                )
            ),
            metrics: metrics
        )
    }

    private func snapshotOutcome(
        status: ClipboardBrokerSnapshotStatus,
        changeCount: Int,
        unsupportedTypes: [String] = [],
        metrics: BrokerMetrics
