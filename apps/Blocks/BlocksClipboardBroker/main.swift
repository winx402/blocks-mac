    private func semanticFileURLsAreRestorable(_ urls: [URL]) -> Bool {
        urls.allSatisfy { url in
            guard url.isFileURL,
                  let values = try? url.resourceValues(forKeys: [
                      .isReadableKey,
                      .isRegularFileKey,
                  ]) else {
                return false
            }
            return values.isReadable == true && values.isRegularFile == true
        }
    }

